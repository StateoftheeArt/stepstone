import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {canonicalHubHash,hubSectionForHash,learningHubMarkup} from '../public/progress-hub.js';
import {homeMarkup} from '../public/home.js';
import {tourRoute} from '../public/tutorial-state.js';

for(const [oldHash,current] of [['#rewards','#progress'],['#rewards/cards','#progress/rewards/cards'],['#rewards-cards','#progress/rewards/cards'],['#rewards-goals','#progress/rewards/goals'],['#rewards-ai','#progress/rewards']]){
  assert.equal(canonicalHubHash(oldHash),current,'Older reward links reach the combined hub.');
  assert.equal(canonicalHubHash(current),current,'Reloading keeps the page and section anchor.');
}
for(const hash of ['#home','#path/math','#lesson/math-8','#join/private-code','#progress'])assert.equal(canonicalHubHash(hash),hash);
assert.equal(hubSectionForHash('#rewards-cards'),'rewards-cards');
assert.equal(canonicalHubHash('#progress/rewards/ai'),'#progress/rewards');
assert.equal(hubSectionForHash('#progress/rewards/ai'),'learning-rewards');
assert.equal(hubSectionForHash('#progress/rewards/goals'),'rewards-goals');
assert.equal(hubSectionForHash('#progress/rewards/not-an-id'),null);
assert.equal(hubSectionForHash('#progress'),null,'Opening Rewards begins at wins, not halfway down the page.');
assert.equal(hubSectionForHash('#progress/rewards'),'learning-rewards','The jump link scrolls within the same page.');
for(const action of ['comfort','profile','mentor','goal'])assert.equal(tourRoute(action),'#progress/rewards');
assert.equal(tourRoute('rewards'),'#progress');
assert.equal(tourRoute('finish'),'#home');

const hub=learningHubMarkup({points:35,modules:2,checks:3,wins:'<p>Completed packing check and mentor note</p>',rewards:'<p>Funded goal and saved claim</p>'});
assert.equal((hub.match(/<h1>/g)||[]).length,1);
assert.match(hub,/<h1>Rewards<\/h1>/);
assert.equal((hub.match(/class="points-value"/g)||[]).length,1,'Wins and rewards use one balance.');
assert.ok(hub.includes('Completed packing check and mentor note'));
assert.ok(hub.includes('Funded goal and saved claim'));
assert.ok(hub.indexOf('Completed packing check')<hub.indexOf('Funded goal'),'Reports are shown before rewards on the same page.');
assert.ok(!hub.includes('data-hub-view'),'There is no separate Wins view selector.');
assert.ok(!hub.includes('aria-current="page"'),'Internal sections are not separate page tabs.');
assert.ok(!hub.includes('rewards-jump'),'Ordinary Rewards has no redundant jump action.');
const guidedWins=learningHubMarkup({guide:true,wins:'<p>Saved skill</p>'});
assert.ok(guidedWins.includes('rewards-jump'),'The onboarding guide keeps its required action target.');
const guide=learningHubMarkup({rewardsOnly:true,rewards:'<h2>Explore goals</h2>'});
assert.ok(!guide.includes('wins-title'),'The reading guide shows only its current reward step.');
assert.match(guide,/aria-label="Reward goals"/);
const zero=learningHubMarkup({points:-3,modules:Infinity,checks:NaN});
assert.ok(!zero.includes('modules completed')&&!zero.includes('checks completed'),'Empty progress counters do not clutter Rewards.');
assert.ok(!zero.includes('NaN')&&!zero.includes('Infinity')&&!zero.includes('>-3<'));
const catalog=JSON.parse(readFileSync(new URL('../public/catalog.json',import.meta.url)));
const next=catalog.units.find(u=>u.id==='math-8');
const intro={phase:0,startedFromPlan:true,rounds:{}};
const source=JSON.stringify(intro);
const page=homeMarkup({catalog,next,draft:intro,done:new Set(),html:String});
assert.equal(page.split(next.goal).length-1,1,'The introductory task is described once.');
assert.ok(page.indexOf('Your task')<page.indexOf('Continue where I left off'));
assert.ok(page.indexOf('resume-objectives')<page.indexOf('resume-actions'),'Numbered sections come before the separated action.');
assert.ok(!page.includes('lesson-preview'),'No empty second panel follows the description.');
assert.equal(JSON.stringify(intro),source);
const practice={phase:2,rounds:{2:{cursor:0,questions:[{id:'saved-question',prompt:'Recover this exact saved question.'}],answers:{'saved-question':'42'},checks:{}}}};
const before=JSON.stringify(practice);
const saved=homeMarkup({catalog,next,draft:practice,done:new Set(),html:String});
assert.ok(saved.indexOf('Recover this exact saved question.')<saved.indexOf('Continue where I left off'));
assert.ok(!saved.includes(next.goal),'The saved question replaces the generic goal.');
assert.equal(JSON.stringify(practice),before,'Rendering never changes a typed answer or question cursor.');
const completed=homeMarkup({catalog,next:null,draft:null,done:new Set(catalog.units.map(u=>u.id)),html:String});
assert.ok(completed.includes('You’ve completed every module.')&&completed.includes('Choose a module to review'));
assert.ok(!completed.includes('Your next lesson')&&!completed.includes('#lesson/undefined'));
console.log('Rewards page shows wins before rewards, preserves older links and one balance, and keeps one saved task description.');
