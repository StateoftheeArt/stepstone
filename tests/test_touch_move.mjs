import assert from 'node:assert/strict';
import {wireMoves} from '../public/touch-move.js';
const listeners=new Map();
const classes={add(){},remove(){}};
const source={disabled:false,classList:classes,setPointerCapture(){},closest(){return this;}};
const destination={classList:classes,closest(){return this;}};
const check={closest(){return null;}};
const host={addEventListener(name,fn){listeners.set(name,fn);},contains(){return true;}};
globalThis.window={addEventListener(){}};
globalThis.document={addEventListener(){},body:{append(){}},createElement(){return {style:{},setAttribute(){},remove(){}};},elementFromPoint(){return destination;}};
let drops=0;
wireMoves(host,{ghost:'carton',onDrop(){drops++;}});
const pointer=(target,x)=>({target,button:0,pointerId:1,clientX:x,clientY:20,preventDefault(){}});
listeners.get('pointerdown')(pointer(source,10));
listeners.get('pointermove')(pointer(source,30));
listeners.get('pointerup')(pointer(source,30));
assert.equal(drops,1,'One drag produces one move.');
const click=target=>{const event={target,blocked:false,preventDefault(){this.blocked=true;},stopImmediatePropagation(){}};listeners.get('click')(event);return event;};
assert.equal(click(check).blocked,false,'Check can be used immediately after dragging.');
assert.equal(click(destination).blocked,false,'A different control remains available.');
assert.equal(click(source).blocked,true,'The generated click does not move a second item.');
assert.equal(click(source).blocked,false,'A deliberate subsequent click remains available.');
console.log('Drag does not double count or block subsequent controls.');
