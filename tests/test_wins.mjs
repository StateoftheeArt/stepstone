import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {configureProfile,profileUnlocks} from '../public/profile.js';
import {firstPasses,previewCompletions,preservePreviewCompletions,groupWins,winsMarkup} from '../public/wins.js';

const catalog=JSON.parse(readFileSync(new URL('../public/catalog.json',import.meta.url)));
configureProfile(JSON.parse(readFileSync(new URL('../public/profile-options.json',import.meta.url))));
const unlocks=profileUnlocks();
const check=(unit,finished,passed=true,extra={})=>({unit,finished,report:{title:unit,score:passed?6:3,total:6,passed,tryNumber:1},...extra});
const reports=[check('math-1',400,false,{note:'Review this <step>.'}),check('reading-1',200),check('math-1',100),check('math-1',300)];
const before=JSON.stringify(reports),completed=firstPasses(reports,unlocks);
assert.deepEqual(completed.map(a=>a.unit),['math-1','reading-1']);
assert.deepEqual(completed[0].pipItems.map(x=>x.key),[]);
assert.deepEqual(completed[1].pipItems.map(x=>x.key),['accessory:sprout']);
assert.equal(JSON.stringify(reports),before,'Rendering preserves input reports and their order.');
const groups=groupWins({catalog,reports,completions:completed,unlocks});
assert.deepEqual(groups.map(s=>[s.id,s.completed]),[['math',1],['reading',1]]);
assert.equal(groups[0].modules.length,1,'Retries stay with one completed module.');
assert.equal(groups[0].modules[0].checks.length,3,'Failed retries remain available as feedback.');
assert.equal(groups[0].modules[0].completion.finished,100,'A later failed check does not erase the original pass.');

const local={'math-1':{result:{score:6,passed:true,at:100}},'reading-1':{result:{score:6,passed:true,at:200}}};
preservePreviewCompletions(local,unlocks);
const archive=JSON.stringify(local['math-1'].firstPass);
local['math-1'].result=null;
assert.equal(previewCompletions(local,unlocks).length,2,'Starting a preview retry keeps its completed module and unlocks.');
local['math-1'].result={score:3,passed:false,at:300};
preservePreviewCompletions(local,unlocks);
assert.equal(JSON.stringify(local['math-1'].firstPass),archive,'A failed retry keeps the first-pass item attribution.');
local['math-1'].result={score:6,passed:true,at:400};
preservePreviewCompletions(local,unlocks);
assert.equal(JSON.stringify(local['math-1'].firstPass),archive,'Passing again does not move or duplicate earned items.');

const markup=winsMarkup({catalog,reports,completions:completed,unlocks,connected:true,formatDate:String});
assert.equal((markup.match(/data-win-subject=/g)||[]).length,2);
assert.equal((markup.match(/data-win-unit="math-1"/g)||[]).length,1);
assert.equal((markup.match(/data-pip-item="accessory:sprout"/g)||[]).length,1);
assert.match(markup,/<details[^>]+data-disclosure-key="wins-math"[^>]*><summary>/);
assert.ok(!markup.includes(' open'),'Subject and feedback sections begin folded.');
assert.ok(markup.includes('Review this &lt;step&gt;.'),'Mentor notes are preserved and escaped.');
assert.match(markup,/Check 1 · 400/);
assert.match(markup,/Checks & mentor feedback \(3\)/);
const retained=winsMarkup({catalog,reports:[],completions:completed,unlocks});
assert.match(retained,/Pack the order/,'An archived module remains visible when its recent checks are gone.');
const failed=groupWins({catalog,reports:[check('science-1',50,false)],unlocks});
assert.equal(failed[0].completed,0);
assert.match(winsMarkup({catalog,reports:[check('science-1',50,false)]}),/Keep practicing/);
assert.match(winsMarkup({catalog,reports,completions:completed}),/Check history/);
const sixth=firstPasses(Array.from({length:6},(_,i)=>check('math-'+(i+1),i+1)),unlocks);
assert.deepEqual(sixth[5].pipItems.map(i=>i.key),['accessory:cap','home.decor:lamp']);assert.ok(sixth.every(win=>win.pipFood===1));
assert.ok(winsMarkup({catalog,completions:sixth,unlocks}).includes('+1 food portion'));assert.ok(!winsMarkup({catalog,completions:sixth,unlocks}).includes('All current Pip items were already unlocked'));
const unsafe=check('unknown-1',1,true);
unsafe.report.title='<img src=x onerror=bad()>';
unsafe.pipItems=[{key:'bad" id="x',label:'<script>bad</script>'}];
const safe=winsMarkup({catalog,completions:[unsafe]});
assert.ok(!safe.includes('<img src=x')&&!safe.includes('<script>'));
assert.match(safe,/&lt;script&gt;bad&lt;\/script&gt;/);
assert.match(winsMarkup({catalog}),/Choose a module/);
const app=readFileSync(new URL('../public/app.js',import.meta.url),'utf8');
assert.match(app,/d\.firstPass\?\.report\?\.passed\|\|d\.result\?\.passed/,'Archived preview passes still count toward access and home items.');
console.log('Subject dropdowns, original item attribution, retry continuity, feedback, archive history and escaping passed.');
