import assert from 'node:assert/strict';
import {createReader,voiceOptions} from '../public/read-aloud.js';

let voices=[],spoken=[],calls=[];
const api={getVoices:()=>voices,cancel(){},speak:value=>spoken.push(value)};
globalThis.window={speechSynthesis:api,addEventListener(){}};
globalThis.speechSynthesis=api;
globalThis.SpeechSynthesisUtterance=class{constructor(text){this.text=text;}};
globalThis.document={body:{append(){}},createElement:()=>({hidden:true,className:'',innerHTML:'',querySelector:selector=>selector==='span'?{textContent:''}:{addEventListener(){}}}),addEventListener(){},getElementById:()=>null};
const remote={voiceURI:'remote-fixture',name:'Online fixture',lang:'en-CA',localService:false};
const local={voiceURI:'local-fixture',name:'Local fixture',lang:'en-CA',localService:true};
const notices=[];
voices=[remote];
const reader=createReader({settings:()=>({voice:'device:auto'}),toast:text=>notices.push(text),softVoice:()=>false});
await reader.read('Fictional learner explanation.');
assert.equal(spoken.length,0,'A device default must not send learner text to an online voice');
assert(notices.some(text=>text.includes('No local English voice')));
voices=[remote,local];
assert(!voiceOptions('soft',true).includes('remote-fixture'));
assert(voiceOptions('soft',true).includes('local-fixture'));
assert(voiceOptions('soft',true).includes('value="soft"'),'The configured Stepstone host voice remains available');
await reader.read('Fictional learner explanation.');
assert.equal(spoken.at(-1).voice,local);
const selectedRemote=createReader({settings:()=>({voice:'device:remote-fixture'}),toast:text=>notices.push(text)});
await selectedRemote.read('Fictional learner explanation.');
assert.equal(spoken.at(-1).voice,local,'An old remote voice preference must use a local voice');
window.AudioContext=class{resume(){return Promise.resolve();}createBufferSource(){return {connect(){},start(){this.onended();},stop(){}};}decodeAudioData(){return Promise.resolve({});}};
globalThis.fetch=async(url,options)=>{calls.push({url,body:JSON.parse(options.body)});return {ok:true,arrayBuffer:async()=>new ArrayBuffer(1)};};
const hosted=createReader({settings:()=>({voice:'soft'}),toast:text=>notices.push(text),softVoice:()=>true});
await hosted.read('Fictional host narration.');
assert.equal(calls.at(-1).url,'/api/read-aloud');
assert.equal(calls.at(-1).body.text,'Fictional host narration.');
globalThis.fetch=async()=>({ok:false,json:async()=>({error:'Fixture host unavailable'})});
await hosted.read('Fictional fallback narration.');
assert.equal(spoken.at(-1).voice,local);
voices=[remote];
const count=spoken.length;
await hosted.read('Fictional fallback narration.');
assert.equal(spoken.length,count,'Failed host narration must not fall back to an online voice');
calls=[];
globalThis.fetch=async()=>{calls.push('unexpected');throw Error('Unexpected host request');};
voices=[local];
const demo=createReader({settings:()=>({voice:'soft'}),toast:text=>notices.push(text),softVoice:()=>true,localOnly:true});
await demo.read('Fictional browser-only narration.');
assert.equal(calls.length,0);
assert.equal(spoken.at(-1).voice,local);
assert(!voiceOptions('soft',true,true).includes('value="soft"'));
console.log('Read-aloud privacy boundaries passed.');
