"""Build Stepstone's layered 64-pixel companion artwork."""
from pathlib import Path
import json
from pip_drawings import MAKERS, ANCHORS

def build():
    art = {maker.__name__: maker() for maker in MAKERS}
    source = '// Generated by tools/build_pips.py; edit tools/pip_drawings.py.\n'
    source += 'const ART='+json.dumps(art,separators=(',',':'))+';\n'
    source += 'export const PIP_ANCHORS='+json.dumps(ANCHORS,separators=(',',':'))+';\n'
    source += 'export function pipArtwork(id){return ART[id]||ART.fox;}\n'
    target = Path(__file__).resolve().parents[1]/'public'/'pip-art.js'
    target.write_text(source,encoding='utf-8',newline='\n')
    print(f'Built {len(art)} detailed 64-pixel companions ({len(source):,} bytes).')

if __name__ == '__main__':
    build()
