def chunk(kind,data): return struct.pack('!I',len(data))+kind+data+struct.pack('!I',zlib.crc32(kind+data)&0xffffffff)
def icon(size,maskable=False):
    pixels=[]
    for y in range(size):
        line=bytearray([0])
        for x in range(size):
            nx,ny=x/size,y/size
            inset=.08 if maskable else 0
            nx=(nx-inset)/(1-2*inset);ny=(ny-inset)/(1-2*inset)
            # Same step silhouette as icon.svg. Platforms apply their own outer mask.
            mark=(14/64<=nx<=51/64 and 35/64<=ny<=47/64) or (26/64<=nx<=51/64 and 24/64<=ny<=47/64) or (38/64<=nx<=51/64 and 13/64<=ny<=47/64)
            t=(x+y)/(2*max(1,size-1))
            first,last=((206,255,243),(90,217,197)) if mark else ((22,75,84),(6,47,58))
            line.extend(round(a+(b-a)*t) for a,b in zip(first,last))
        pixels.append(line)
    raw=b''.join(pixels)
    return b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('!IIBBBBB',size,size,8,2,0,0,0))+chunk(b'IDAT',zlib.compress(raw))+chunk(b'IEND',b'')
def windows_icon():
    """PNG-backed ICO sizes for Windows desktop, Start, and high-DPI displays."""
    sizes=(16,24,32,48,64,128,256)
    images=[icon(size) for size in sizes]
    offset=6+16*len(images)
    entries=[]
    for size,data in zip(sizes,images):
        entries.append(struct.pack('<BBBBHHII',size%256,size%256,0,0,1,24,len(data),offset))
        offset+=len(data)
    return struct.pack('<HHH',0,1,len(images))+b''.join(entries)+b''.join(images)

